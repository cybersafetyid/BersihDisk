export function Icon({ name, size = 18, color, className }: IconProps) {
  const style = { width: size, height: size, flexShrink: 0 };

  // Lucide UI icons (stroke).
  if (name in lucidePaths) {
    return (
      <svg
        viewBox="0 0 24 24"
        fill="none"
        stroke={color ?? "currentColor"}
        strokeWidth="2"
        strokeLinecap="round"
        strokeLinejoin="round"
        style={style}
        className={className}
        aria-hidden="true"
      >
        {lucidePaths[name]}
      </svg>
    );
  }

  // simple-icons brand icons (fill), e.g. "gradle".
  const si = brandIcons[name];
  if (si?.path) {
    return (
      <svg
        viewBox="0 0 24 24"
        fill={color ?? "currentColor"}
        style={style}
        className={className}
        role="img"
        aria-label={si.title ?? name}
      >
        <path d={si.path} />
      </svg>
    );
  }

  // Fallback: empty box so layout stays stable.
  return <svg viewBox="0 0 24 24" style={style} className={className} aria-hidden="true" />;
}
